/* ------------------------------------------------------------------ *
 * Selectors
 * ------------------------------------------------------------------ */

export function getArticles(): Article[] {
  return [...articles].sort(
    (a, b) => new Date(b.date).getTime() - new Date(a.date).getTime(),
  );
}

export function getArticle(slug: string): Article | undefined {
  return articles.find((a) => a.slug === slug);
}

export function getLatestArticles(count = 3): Article[] {
  return getArticles().slice(0, count);
}

export function getRelatedArticles(slug: string, count = 3): Article[] {
  const current = getArticle(slug);
  if (!current) return getLatestArticles(count);

  const scored = getArticles()
    .filter((a) => a.slug !== slug)
    .map((a) => ({
      article: a,
      score:
        (a.category === current.category ? 2 : 0) +
        a.tags.filter((t) => current.tags.includes(t)).length,
    }))
    .sort((a, b) => b.score - a.score);

  return scored.slice(0, count).map((s) => s.article);
}

/** Categories that currently have at least one published article. */
export function getActiveCategories(): string[] {
  return Array.from(new Set(getArticles().map((a) => a.category)));
}

/** Rough reading time in minutes — shown on article pages (§32). */
export function getReadingTime(article: Article): number {
  const words = article.body.join(" ").split(/\s+/).length;
  return Math.max(1, Math.round(words / 200));
}
